"""Embed the maintained PSL snapshot as ordinary HTTP library data."""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DIRECTORY = ROOT / "sysroot/vendor/publicsuffix"


def main() -> None:
    source = (DIRECTORY / "public_suffix_list.dat").read_text(encoding="utf-8")
    lines = []
    for raw in source.splitlines():
        line = raw.strip()
        if not line:
            continue
        if line.startswith("//") and not line.startswith(("// ===", "// VERSION:", "// COMMIT:")):
            continue
        lines.append(json.dumps(line + "\n", ensure_ascii=False))
    output = (
        "/* Generated by scripts/generate_public_suffix.py.\n"
        " * PSL data: Mozilla Public License 2.0; see LICENSE. */\n" + "\n".join(lines) + "\n"
    )
    (DIRECTORY / "public_suffix_list.inc").write_text(output, encoding="utf-8")


if __name__ == "__main__":
    main()
