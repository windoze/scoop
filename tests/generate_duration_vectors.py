"""Generate Duration arithmetic expectations using independent integer nanoseconds."""

from pathlib import Path
from random import Random

NANOS = 10**9
MINIMUM = -(2**63) * NANOS
MAXIMUM = (2**63) * NANOS - 1
DESTINATION = Path(__file__).parent / "fixtures/m42-duration/arithmetic/program/src"


def parts(value: int) -> str:
    seconds, nanos = divmod(value, NANOS)
    return f"({seconds}L, {nanos})"


def expected(value: int | None) -> str:
    if value is None or not MINIMUM <= value <= MAXIMUM:
        return "None"
    return f"Some({parts(value)})"


def quotient(value: int, divisor: int) -> int | None:
    if divisor == 0:
        return None
    magnitude = abs(value) // abs(divisor)
    return -magnitude if (value < 0) != (divisor < 0) else magnitude


def write_batches(prefix: str, lines: list[str]) -> None:
    for index in range(len(lines) // 20):
        body = "\n".join("    " + line for line in lines[index * 20 : (index + 1) * 20])
        source = f"// Generated by tests/generate_duration_vectors.py.\nfun {prefix}Vectors{index}() {{\n{body}\n}}\n"
        (DESTINATION / f"{prefix}_{index}.scoop").write_text(source)


def main() -> None:
    rng = Random(42010)
    edges = [MINIMUM, MINIMUM + 1, MAXIMUM - 1, MAXIMUM, -NANOS - 1, -1, 0, 1, NANOS - 1]
    pairs = [(a, b) for a in edges[:4] for b in edges[:4]]
    pairs += [(MINIMUM + NANOS - 1, -1), (MAXIMUM, 1), (-1, MAXIMUM), (0, MINIMUM)]
    for _ in range(40):
        a = rng.randrange(MINIMUM, MAXIMUM + 1)
        b = rng.choice(edges) if rng.randrange(2) else rng.randrange(MINIMUM, MAXIMUM + 1)
        pairs.append((a, b))
    write_batches(
        "add",
        [
            f"addition({parts(a)}, {parts(b)}, {expected(a + b)}, {expected(a - b)})"
            for a, b in pairs
        ],
    )
    factors = [-(2**63), 2**63 - 1, -1000000001, -3, -1, 0, 1, 3, 1000000001]
    scales = [
        (a, b)
        for a in [MINIMUM, MINIMUM + 1, MAXIMUM, -1, 1, NANOS - 1]
        for b in [-1, 1, -(2**63), 2**63 - 1]
    ]
    scales += [(0, 0), (MAXIMUM, 0), (MINIMUM, 0), (-1, 3), (1, -3), (MAXIMUM, 3)]
    while len(scales) < 80:
        a = rng.randrange(MINIMUM, MAXIMUM + 1)
        b = rng.choice(factors) if rng.randrange(2) else rng.randrange(-(2**63), 2**63)
        scales.append((a, b))
    write_batches(
        "scale",
        [
            f"scaling({parts(a)}, {b}L, {expected(a * b)}, {expected(quotient(a, b))})"
            for a, b in scales
        ],
    )


if __name__ == "__main__":
    main()
