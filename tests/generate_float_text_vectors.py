"""Regenerate M42 text fixtures offline; the fixture runner never invokes this.

An independent Fraction oracle binary-searches adjacent IEEE values and compares
exact distances, including the virtual successor above the largest finite value.
Host floating point is only used to spell an already selected expected bit pattern.
"""

import random
import struct
from fractions import Fraction
from pathlib import Path


def power2(exponent):
    return Fraction(2**exponent) if exponent >= 0 else Fraction(1, 2**-exponent)


def binary_value(bits, precision, exponent_bits):
    fraction_bits = precision - 1
    exponent = bits >> fraction_bits
    fraction = bits & ((1 << fraction_bits) - 1)
    bias = (1 << (exponent_bits - 1)) - 1
    if exponent == 0:
        return fraction * power2(1 - bias - fraction_bits)
    return ((1 << fraction_bits) + fraction) * power2(exponent - bias - fraction_bits)


def closest_bits(value, precision, exponent_bits):
    infinity = ((1 << exponent_bits) - 1) << (precision - 1)
    low, high = 0, infinity
    while low + 1 < high:
        middle = (low + high) // 2
        if binary_value(middle, precision, exponent_bits) <= value:
            low = middle
        else:
            high = middle
    lower = binary_value(low, precision, exponent_bits)
    upper = binary_value(high, precision, exponent_bits)
    down, up = value - lower, upper - value
    if down < up or (down == up and low % 2 == 0):
        return low
    return high


def decimal_text(value):
    """Exact terminating decimal for a nonnegative rational with denominator 2^k."""
    denominator = value.denominator
    assert denominator & (denominator - 1) == 0
    places = denominator.bit_length() - 1
    digits = str(value.numerator * 5**places)
    return digits if places == 0 else digits + "e-" + str(places)


def samples(precision, exponent_bits):
    normal = 1 << (precision - 1)
    infinity = ((1 << exponent_bits) - 1) << (precision - 1)
    one = ((1 << (exponent_bits - 1)) - 1) << (precision - 1)
    # Zero/subnormal, the normal boundary, binade changes, ties of both parities,
    # and overflow. Perturb well below a Double ulp to catch double rounding.
    boundaries = [
        0,
        1,
        2,
        normal - 2,
        normal - 1,
        normal,
        one - 1,
        one,
        one + 1,
        one + 2,
        2 * one // 3,
        infinity - 2,
        infinity - 1,
    ]
    rows = []
    for bits in boundaries:
        lower = binary_value(bits, precision, exponent_bits)
        upper = binary_value(bits + 1, precision, exponent_bits)
        halfway = (lower + upper) / 2
        epsilon = (upper - lower) / 2**100
        for value in (lower, halfway - epsilon, halfway, halfway + epsilon):
            rows.append(decimal_text(value))
    # Both sides of a midpoint after more than either format's retained digits.
    for bits in (0, normal - 1, one, one + 1, infinity - 1):
        lower = binary_value(bits, precision, exponent_bits)
        upper = binary_value(bits + 1, precision, exponent_bits)
        halfway = (lower + upper) / 2
        epsilon = (upper - lower) / 2**2200
        rows.extend(decimal_text(value) for value in (halfway - epsilon, halfway + epsilon))
    rng = random.Random(42007 + precision)
    for _ in range(100):
        digits = "".join(str(rng.randrange(10)) for _ in range(rng.randrange(1, 90)))
        order = rng.randrange(-70, 65) if precision == 24 else rng.randrange(-360, 340)
        rows.append(digits + "e" + str(order - len(digits) + 1))
    return rows


def generate(precision, exponent_bits, width):
    root = Path(__file__).resolve().parent / "fixtures" / "m42-text" / f"float{width}"
    source = root / "program" / "src"
    source.mkdir(parents=True, exist_ok=True)
    kind = "Float" if width == 32 else "Double"
    suffix = "f" if width == 32 else ""
    infinity = ((1 << exponent_bits) - 1) << (precision - 1)
    cases = []
    for spelling in samples(precision, exponent_bits):
        expected = closest_bits(Fraction(spelling), precision, exponent_bits)
        # Exercise both signs for every exact oracle vector.
        for negative in (False, True):
            text = ("-" if negative else "") + spelling
            if expected == infinity:
                cases.append(f'    reject("{text}")')
            else:
                bits = expected | (int(negative) << (width - 1))
                value = struct.unpack(
                    ">f" if width == 32 else ">d", bits.to_bytes(width // 8, "big")
                )[0]
                cases.append(f'    expect("{text}", {value!r}{suffix})')
    functions = []
    for start in range(0, len(cases), 48):
        name = f"vectors{start // 48}"
        functions.append(name)
        content = "// Generated by tests/generate_float_text_vectors.py; exact Fraction oracle.\n"
        content += f"fun {name}() {{\n" + "\n".join(cases[start : start + 48]) + "\n}\n"
        (source / f"vectors_{start // 48}.scoop").write_text(content)
    main = f"""import scoop.text.*

fun check(value: Boolean, label: String) {{ if (!value) {{ println(label); throw Exception(Some(label)) }} }}
fun expect(text: String, expected: {kind}) {{
    val value = text.to{kind}()
    check(value == expected, text)
    if (value == 0{suffix if suffix else ".0"}) check(1{suffix if suffix else ".0"} / value == 1{suffix if suffix else ".0"} / expected, "zero sign: " + text)
}}
fun reject(text: String) {{ check(text.to{kind}OrNull() == None, "overflow: " + text) }}
fun main() {{
"""
    main += "\n".join(f"    {name}()" for name in functions)
    main += f'\n    println("text float{width} passed")\n}}\n'
    (source / "main.scoop").write_text(main)
    print(f"float{width}: {len(cases)} exact vectors")


if __name__ == "__main__":
    generate(24, 8, 32)
    generate(53, 11, 64)
