use scoop_source::Span;
use scoop_syntax::SyntaxKind;

use super::TokenKind;

#[derive(Debug, Clone, Copy)]
pub(crate) struct Lexeme {
    pub kind: SyntaxKind,
    pub span: Span,
}

impl TokenKind {
    pub(crate) fn syntax_kind(&self) -> SyntaxKind {
        match self {
            Self::Error => SyntaxKind::InvalidToken,
            Self::Package => SyntaxKind::KwPackage,
            Self::Import => SyntaxKind::KwImport,
            Self::Suspend => SyntaxKind::KwSuspend,
            Self::Vararg => SyntaxKind::KwVararg,
            Self::Fun => SyntaxKind::KwFun,
            Self::Struct => SyntaxKind::KwStruct,
            Self::Enum => SyntaxKind::KwEnum,
            Self::Class => SyntaxKind::KwClass,
            Self::Interface => SyntaxKind::KwInterface,
            Self::Val => SyntaxKind::KwVal,
            Self::Var => SyntaxKind::KwVar,
            Self::If => SyntaxKind::KwIf,
            Self::Else => SyntaxKind::KwElse,
            Self::When => SyntaxKind::KwWhen,
            Self::While => SyntaxKind::KwWhile,
            Self::Do => SyntaxKind::KwDo,
            Self::For => SyntaxKind::KwFor,
            Self::Break => SyntaxKind::KwBreak,
            Self::Continue => SyntaxKind::KwContinue,
            Self::Return => SyntaxKind::KwReturn,
            Self::True => SyntaxKind::KwTrue,
            Self::False => SyntaxKind::KwFalse,
            Self::This => SyntaxKind::KwThis,
            Self::Is => SyntaxKind::KwIs,
            Self::In => SyntaxKind::KwIn,
            Self::Infix => SyntaxKind::KwInfix,
            Self::As => SyntaxKind::KwAs,
            Self::Ident(_) => SyntaxKind::Ident,
            Self::EscapedIdent(_) => SyntaxKind::EscapedIdent,
            Self::Str(_) => SyntaxKind::String,
            Self::FStringStart => SyntaxKind::FStringStart,
            Self::FStringText(_) => SyntaxKind::FStringText,
            Self::InterpolationStart => SyntaxKind::InterpolationStart,
            Self::InterpolationEnd => SyntaxKind::InterpolationEnd,
            Self::FStringEnd => SyntaxKind::FStringEnd,
            Self::Char(_) => SyntaxKind::Char,
            Self::Int(_) => SyntaxKind::Integer,
            Self::Float(_) => SyntaxKind::Float,
            Self::LParen => SyntaxKind::LParen,
            Self::RParen => SyntaxKind::RParen,
            Self::LBrace => SyntaxKind::LBrace,
            Self::RBrace => SyntaxKind::RBrace,
            Self::LBracket => SyntaxKind::LBracket,
            Self::RBracket => SyntaxKind::RBracket,
            Self::Comma => SyntaxKind::Comma,
            Self::Semicolon => SyntaxKind::Semicolon,
            Self::Colon => SyntaxKind::Colon,
            Self::DoubleColon => SyntaxKind::DoubleColon,
            Self::At => SyntaxKind::At,
            Self::Dot => SyntaxKind::Dot,
            Self::DotDot => SyntaxKind::DotDot,
            Self::DotDotLess => SyntaxKind::DotDotLess,
            Self::Arrow => SyntaxKind::Arrow,
            Self::Question => SyntaxKind::Question,
            Self::QuestionDot => SyntaxKind::QuestionDot,
            Self::QuestionColon => SyntaxKind::QuestionColon,
            Self::Plus => SyntaxKind::Plus,
            Self::PlusPlus => SyntaxKind::PlusPlus,
            Self::PlusEqual => SyntaxKind::PlusEqual,
            Self::Minus => SyntaxKind::Minus,
            Self::MinusMinus => SyntaxKind::MinusMinus,
            Self::MinusEqual => SyntaxKind::MinusEqual,
            Self::Star => SyntaxKind::Star,
            Self::StarEqual => SyntaxKind::StarEqual,
            Self::Slash => SyntaxKind::Slash,
            Self::SlashEqual => SyntaxKind::SlashEqual,
            Self::Percent => SyntaxKind::Percent,
            Self::PercentEqual => SyntaxKind::PercentEqual,
            Self::Bang => SyntaxKind::Bang,
            Self::BangIn => SyntaxKind::BangIn,
            Self::BangEqual => SyntaxKind::BangEqual,
            Self::BangEqualEqual => SyntaxKind::BangEqualEqual,
            Self::Equal => SyntaxKind::Equal,
            Self::EqualEqual => SyntaxKind::EqualEqual,
            Self::EqualEqualEqual => SyntaxKind::EqualEqualEqual,
            Self::Less => SyntaxKind::Less,
            Self::LessEqual => SyntaxKind::LessEqual,
            Self::Greater => SyntaxKind::Greater,
            Self::GreaterEqual => SyntaxKind::GreaterEqual,
            Self::AmpAmp => SyntaxKind::AmpAmp,
            Self::PipePipe => SyntaxKind::PipePipe,
            Self::Eof => SyntaxKind::Eof,
        }
    }
}
