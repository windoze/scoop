//! Borrowed facts used by the shared logical body projection.

use crate::*;
use la_arena::Arena;

/// Completed frontend facts, independent of successful module publication.
#[derive(Clone, Copy)]
pub struct HirBodyProjectionInputs<'a> {
    pub extern_functions: &'a Arena<ExternFunction>,
    pub export_default_exprs: &'a Arena<ExportDefaultExpr>,
    pub export_default_sources: &'a Arena<ExportDefaultSource>,
    pub type_inputs: HirTypeIdentityInputs<'a>,
    pub sources: HirSourceProjectionInputs<'a>,
    pub anonymous_functions: &'a Arena<AnonymousFunction>,
    pub bound_callable_refs: &'a Arena<BoundCallableRef>,
    pub callable_references: &'a Arena<CallableReference>,
    pub callback_registration_identities: &'a HirCallbackRegistrationIdentities,
    pub class_applications: &'a Arena<ClassApplication>,
    pub class_constructor_applications: &'a Arena<ClassConstructorApplication>,
    pub class_constructors: &'a Arena<ClassConstructor>,
    pub constructor_identities: &'a HirConstructorIdentities,
    pub default_local_value_scopes: &'a Arena<DefaultLocalValueScope>,
    pub derived_equality_applications: &'a Arena<DerivedEqualityApplication>,
    pub enum_applications: &'a Arena<EnumApplication>,
    pub enum_member_identities: &'a HirEnumMemberIdentities,
    pub foreign_callback_registrations: &'a Arena<ForeignCallbackRegistration>,
    pub function_coercions: &'a Arena<FunctionCoercion>,
    pub function_identities: &'a HirFunctionIdentities,
    pub function_types: &'a Arena<FunctionType>,
    pub functions: &'a Arena<Function>,
    pub generic_delegate_templates: &'a Arena<GenericDelegateTemplate>,
    pub generic_functions: &'a Arena<GenericFunction>,
    pub generic_method_applications: &'a Arena<GenericMethodApplication>,
    pub generic_methods: &'a Arena<GenericMethod>,
    pub globals: &'a Arena<Global>,
    pub imported_constructor_templates: &'a Arena<ImportedConstructorTemplate>,
    pub imported_dependency_callables: &'a Arena<ImportedDependencyCallableUse>,
    pub imported_generic_applications: &'a Arena<ImportedGenericCallableApplication>,
    pub imported_generic_delegate_templates: &'a Arena<ImportedGenericDelegateTemplate>,
    pub imported_generic_templates: &'a Arena<ImportedGenericCallableTemplate>,
    pub initialization_unit_identities: &'a HirInitializationUnitIdentities,
    pub initialization_units: &'a Arena<InitializationUnit>,
    pub instantiations: &'a Arena<ResolvedGenericFunction>,
    pub interface_applications: &'a Arena<InterfaceApplication>,
    pub lambdas: &'a Arena<Lambda>,
    pub local_functions: &'a Arena<LocalFunction>,
    pub member_requirement_implementations: &'a Arena<MemberRequirementImplementation>,
    pub member_requirement_owners:
        &'a std::collections::HashMap<MemberRequirementId, MemberRequirementOwner>,
    pub method_applications: &'a Arena<MethodApplication>,
    pub object_types: &'a Arena<ObjectType>,
    pub object_value_identities: &'a HirObjectValueIdentities,
    pub property_accessor_identities: &'a HirPropertyAccessorIdentities,
    pub property_identities: &'a HirPropertyIdentities,
    pub singleton_values: &'a Arena<SingletonValue>,
    pub struct_applications: &'a Arena<StructApplication>,
    pub struct_constructor_applications: &'a Arena<StructConstructorApplication>,
    pub struct_constructors: &'a Arena<StructConstructor>,
    pub types: &'a Arena<Type>,
}

impl<'a> HirBodyProjectionInputs<'a> {
    pub fn from_export(export: &'a ExportHir) -> Self {
        Self {
            extern_functions: &export.extern_functions,
            export_default_exprs: &export.export_default_exprs,
            export_default_sources: &export.export_default_sources,
            type_inputs: HirTypeIdentityInputs::from_export(export),
            sources: HirSourceProjectionInputs::from_export(export),
            anonymous_functions: &export.anonymous_functions,
            bound_callable_refs: &export.bound_callable_refs,
            callable_references: &export.callable_references,
            callback_registration_identities: &export.callback_registration_identities,
            class_applications: &export.class_applications,
            class_constructor_applications: &export.class_constructor_applications,
            class_constructors: &export.class_constructors,
            constructor_identities: &export.constructor_identities,
            default_local_value_scopes: &export.default_local_value_scopes,
            derived_equality_applications: &export.derived_equality_applications,
            enum_applications: &export.enum_applications,
            enum_member_identities: &export.enum_member_identities,
            foreign_callback_registrations: &export.foreign_callback_registrations,
            function_coercions: &export.function_coercions,
            function_identities: &export.function_identities,
            function_types: &export.function_types,
            functions: &export.functions,
            generic_delegate_templates: &export.generic_delegate_templates,
            generic_functions: &export.generic_functions,
            generic_method_applications: &export.generic_method_applications,
            generic_methods: &export.generic_methods,
            globals: &export.globals,
            imported_constructor_templates: &export.imported_constructor_templates,
            imported_dependency_callables: &export.imported_dependency_callables,
            imported_generic_applications: &export.imported_generic_applications,
            imported_generic_delegate_templates: &export.imported_generic_delegate_templates,
            imported_generic_templates: &export.imported_generic_templates,
            initialization_unit_identities: &export.initialization_unit_identities,
            initialization_units: &export.initialization_units,
            instantiations: &export.instantiations,
            interface_applications: &export.interface_applications,
            lambdas: &export.lambdas,
            local_functions: &export.local_functions,
            member_requirement_implementations: &export.member_requirement_implementations,
            member_requirement_owners: &export.member_requirement_owners,
            method_applications: &export.method_applications,
            object_types: &export.object_types,
            object_value_identities: &export.object_value_identities,
            property_accessor_identities: &export.property_accessor_identities,
            property_identities: &export.property_identities,
            singleton_values: &export.singleton_values,
            struct_applications: &export.struct_applications,
            struct_constructor_applications: &export.struct_constructor_applications,
            struct_constructors: &export.struct_constructors,
            types: &export.types,
        }
    }

    pub(crate) fn callable_function(&self, callable: Callable) -> FunctionId {
        crate::callable_function_in(
            callable,
            self.instantiations,
            self.generic_functions,
            self.method_applications,
            self.generic_method_applications,
            self.generic_methods,
        )
    }
}
