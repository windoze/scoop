//! 名称解析（AST → resolved symbols）。
//!
//! 本模块覆盖编译管线的 `resolve` 阶段：把源码中的标识符路径绑定到具体的
//! 声明符号上。解析是**两阶段**的：
//!
//! 1. **headers**：收集所有顶层声明（跨文件、跨 cone）到 [`Index`]，解析声明头
//!    （超类型、函数签名、属性类型等）里的类型引用；
//! 2. **bodies**：在函数体 / 初始化器内部解析名字，允许前向引用同文件顶层符号。
//!
//! 解析结果以“resolved 引用”的形式写回（供 typecheck 消费），并把所有失败
//! 汇报为稳定诊断码（`scoop::resolve::*`）。
//!
//! 当前文件只导出 [`errors`] 中的诊断构造辅助函数；`Index` / import 表 /
//! 作用域栈 / 可见性等核心数据结构在名称解析阶段（Phase B）补齐。

